// Run: npm test   (starts its own server on a temp database; your data/db.json is untouched)
const {spawn}=require('child_process'),fs=require('fs'),os=require('os'),path=require('path');
const tmpDb=n=>path.join(os.tmpdir(),'fd-test-'+process.pid+'-'+n+'.json');
const seed=()=>{const d=JSON.parse(fs.readFileSync(path.join(__dirname,'data','db.json'),'utf8'));d.orders=[];return d;};
let pass=0,fail=0,BASE='',tok='';
const ok=(c,m)=>{c?pass++:fail++;console.log((c?'  ok   ':'  FAIL ')+m);};
const call=async(m,u,b,t=tok,raw)=>{const r=await fetch(BASE+u,{method:m,headers:{'Content-Type':'application/json',...(t?{Authorization:'Bearer '+t}:{})},body:raw!==undefined?raw:b===undefined?undefined:JSON.stringify(b)});let j={};try{j=await r.json();}catch{}return{s:r.status,j,h:r.headers};};
function start(env,port){return new Promise(res=>{const p=spawn(process.execPath,['server.js'],{cwd:__dirname,env:{...process.env,ADMIN_PASS:'admin123',NODE_ENV:'',ALLOW_DEMO:'',PORT:port,...env}});let out='';
  p.stdout.on('data',d=>{out+=d;if(out.includes('http://localhost'))res(p);});p.on('exit',c=>{if(!out.includes('http://localhost'))res({exitCode:c});});});}
(async()=>{
  const dbFile=tmpDb('a');fs.writeFileSync(dbFile,JSON.stringify(seed()));
  const srv=await start({DB_PATH:dbFile},3456);BASE='http://localhost:3456';
  console.log('Auth');
  ok((await call('GET','/api/data',undefined,'')).s===401,'no token is rejected');
  ok((await call('GET','/api/data',undefined,'fake')).s===401,'bad token is rejected');
  ok((await call('POST','/api/login',undefined,'')).s===401,'login with no body is rejected');
  ok((await call('POST','/api/login',{password:'nope'},'')).s===401,'wrong password is rejected');
  ok((await call('POST','/api/login',{password:12345},'')).s===401,'non-string password is rejected');
  ok((await call('POST','/api/login',{password:''},'')).s===401,'empty password is rejected');
  const l=await call('POST','/api/login',{password:'admin123'},'');tok=l.j.token;
  ok(l.s===200&&/^[0-9a-f]{64}$/.test(tok||''),'correct password returns a random 64-char token');
  ok((await call('POST','/api/login',undefined,'',"{bad json")).s===400,'malformed JSON gives 400, not a crash');
  ok((await call('POST','/api/menu',undefined,tok,JSON.stringify({name:'x'.repeat(20000)}))).s===413,'oversized body gives 413');
  console.log('Menu: adding');
  const add=b=>call('POST','/api/menu',b);
  let r=await add({name:'Dosa',category:'Tiffin',price:'50.5'});
  ok(r.s===200&&r.j.price===50.5&&r.j.available===true,'valid item (price as string) is added');
  const dosa=r.j.id;
  ok((await add({name:'  Idli   Set ',price:30})).j.name==='Idli Set','extra spaces are trimmed');
  ok((await add({price:10})).s===400,'missing name rejected');
  ok((await add({name:'   ',price:10})).s===400,'blank name rejected');
  ok((await add({name:'Vada'})).s===400,'missing price rejected');
  for(const p of [0,-5,'abc','',null,true,[5],{},1e9,100001])ok((await add({name:'Bad',price:p})).s===400,'price '+JSON.stringify(p)+' rejected');
  ok((await add({name:'x'.repeat(61),price:10})).s===400,'61-char name rejected');
  ok((await add({name:'y'.repeat(60),price:10})).s===200,'60-char name accepted');
  ok((await add({name:'Cat',category:'c'.repeat(31),price:10})).s===400,'31-char category rejected');
  ok((await add({name:'Cat2',category:123,price:10})).s===400,'non-text category rejected');
  ok((await add({name:'DOSA',price:10})).s===409,'duplicate name (any case) rejected');
  r=await add({name:'<img src=x onerror=alert(1)>',price:10});
  ok(r.s===200&&r.j.name.includes('<img'),'HTML is stored as text (escaped when displayed)');
  console.log('Menu: editing and deleting');
  const pm=(id,b)=>call('PATCH','/api/menu/'+id,b);
  ok((await pm(dosa,{price:60})).j.price===60,'price update works');
  ok((await pm(dosa,{price:0})).s===400,'price update to 0 rejected');
  ok((await pm(dosa,{price:'x'})).s===400,'non-numeric price update rejected');
  ok((await pm(dosa,{available:'no'})).s===400,'non-boolean availability rejected');
  ok((await pm(dosa,{})).s===400,'empty update rejected');
  ok((await pm(dosa,{price:70,available:'no'})).s===400&&(await call('GET','/api/data')).j.menu.find(m=>m.id===dosa).price===60,'a bad update changes nothing');
  ok((await pm(99999,{price:5})).s===404,'unknown item gives 404');
  ok((await pm('abc',{price:5})).s===404,'non-numeric id gives 404');
  ok((await call('DELETE','/api/menu/'+dosa)).s===200,'delete works');
  ok((await call('DELETE','/api/menu/'+dosa)).s===404,'deleting twice gives 404');
  console.log('Orders');
  const menu=(await call('GET','/api/data')).j.menu;
  for(const m of menu)await pm(m.id,{available:false});
  ok((await call('POST','/api/orders/demo')).s===400,'no demo order when everything is sold out');
  for(const m of menu)await pm(m.id,{available:true});
  const o=(await call('POST','/api/orders/demo')).j,po=(id,b)=>call('PATCH','/api/orders/'+id,b);
  ok(o.id>=1001&&o.status==='New'&&Math.abs(o.total-o.items.reduce((s,i)=>s+i.qty*i.price,0))<0.001,'demo order has a correct total');
  ok((await po(o.id,{status:'Foo'})).s===400,'unknown status rejected');
  ok((await po(o.id,{status:'Delivered'})).s===409,'cannot skip New to Delivered');
  ok((await po(o.id,{status:'Out for delivery'})).s===409,'cannot skip New to Out for delivery');
  ok((await po(o.id,{status:'New'})).s===409,'cannot repeat the same status');
  ok((await po(o.id,{})).s===400,'empty order update rejected');
  ok((await po(o.id,{driver:'Hacker'})).s===400,'unknown driver rejected');
  ok((await po(o.id,{status:'Preparing'})).s===200,'New to Preparing works');
  r=await po(o.id,{status:'Out for delivery'});
  ok(r.s===400&&(await call('GET','/api/data')).j.orders[0].status==='Preparing','out for delivery needs a driver (status unchanged)');
  ok((await po(o.id,{driver:'Arun'})).s===200,'driver assignment works');
  ok((await po(o.id,{status:'Out for delivery'})).s===200,'Preparing to Out for delivery works');
  ok((await po(o.id,{status:'Delivered'})).s===200,'Out for delivery to Delivered works');
  ok((await po(o.id,{status:'Cancelled'})).s===409,'delivered order cannot be cancelled');
  ok((await po(o.id,{driver:'Meena'})).s===409,'delivered order cannot change driver');
  ok((await po(424242,{status:'Preparing'})).s===404,'unknown order gives 404');
  const o2=(await call('POST','/api/orders/demo')).j;
  ok((await po(o2.id,{status:'Cancelled'})).s===200&&(await po(o2.id,{status:'New'})).s===409,'cancelled order cannot be revived');
  const before=(await call('GET','/api/data')).j.orders.length;
  const par=await Promise.all(Array.from({length:60},()=>call('POST','/api/orders/demo')));
  const ids=new Set(par.map(x=>x.j.id));
  const disk=JSON.parse(fs.readFileSync(dbFile,'utf8')),api=(await call('GET','/api/data')).j;
  ok(par.every(x=>x.s===200)&&ids.size===60,'60 simultaneous orders all succeed with unique ids');
  ok(disk.orders.length===before+60&&api.orders.length===disk.orders.length,'database file is valid and matches the API');
  console.log('Limits and misc');
  let full=0;for(let i=0;i<210;i++){const x=await add({name:'Item '+i,price:1});if(x.s===400&&/full/.test(x.j.error)){full=1;break;}}
  ok(full===1&&(await call('GET','/api/data')).j.menu.length===200,'menu is capped at 200 items');
  r=await call('GET','/api/nothing');ok(r.s===404&&r.j.error,'unknown API route gives JSON 404');
  r=await fetch(BASE+'/');ok(r.status===200&&/frame-ancestors/.test(r.headers.get('content-security-policy')||'')&&!r.headers.get('x-powered-by'),'page loads with security headers');
  ok((await fetch(BASE+'/data/db.json')).status===404,'database file is not downloadable');
  ok((await fetch(BASE+'/%2e%2e/server.js')).status!==200,'path traversal is blocked');
  ok((await call('POST','/api/logout')).s===200&&(await call('GET','/api/data')).s===401,'logout invalidates the token');
  console.log('Login lockout');
  for(let i=0;i<5;i++)await call('POST','/api/login',{password:'bad'+i},'');
  ok((await call('POST','/api/login',{password:'bad'},'')).s===429,'6th wrong attempt is locked out');
  ok((await call('POST','/api/login',{password:'admin123'},'')).s===429,'even the right password is refused during lockout');
  srv.kill();
  console.log('Production mode and startup');
  let x=await start({NODE_ENV:'production',DB_PATH:dbFile,PORT:3457},3457);
  ok(x.exitCode===1,'production refuses to start with the default password');
  const f2=tmpDb('b');fs.writeFileSync(f2,'{bad');x=await start({DB_PATH:f2},3458);
  ok(x.exitCode===1,'a corrupted database stops the server with a clear error');
  const f3=tmpDb('c');fs.writeFileSync(f3,JSON.stringify(seed()));
  const p3=await start({NODE_ENV:'production',ADMIN_PASS:'s3cret',DB_PATH:f3},3459);BASE='http://localhost:3459';
  tok=(await call('POST','/api/login',{password:'s3cret'},'')).j.token;
  ok(tok&&(await call('POST','/api/orders/demo')).s===404,'demo orders are off in production');
  p3.kill();
  console.log('\n'+pass+' passed, '+fail+' failed');
  process.exit(fail?1:0);
})();
